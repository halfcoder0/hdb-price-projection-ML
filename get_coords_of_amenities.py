"""
Fetch Singapore location data from OpenStreetMap via the Overpass API.
Retrieves MRT/LRT stations, shopping malls, bus stations/interchanges,
hawker centres, and schools, saving each to a separate CSV file.

No API key required.
"""

import requests
import pandas as pd
import time


# Changi Airport Skytrain station names (private APM, not public MRT/LRT)
CHANGI_SKYTRAIN_STATIONS = {"a", "a south", "b", "c", "d", "e", "f"}

# Sentosa Express station names (tourist monorail, not public MRT/LRT)
SENTOSA_EXPRESS_STATIONS = {
    "beach station",
    "waterfront station",
    "imbiah station",
    "resorts world station",
}


def query_overpass(query: str, timeout: int = 90) -> list:
    """
    Execute an Overpass API query and return the elements.

    Parameters
    ----------
    query : str
        The Overpass QL query
    timeout : int
        Request timeout in seconds

    Returns
    -------
    list of dict
        Elements from the Overpass API response
    """
    overpass_url = "https://overpass-api.de/api/interpreter"

    try:
        resp = requests.post(overpass_url, data={"data": query}, timeout=timeout)
        resp.raise_for_status()
        return resp.json().get("elements", [])
    except Exception as e:
        print(f"Error querying Overpass API: {e}")
        return []


def get_coordinates(element: dict) -> tuple:
    """
    Extract lat/lon from an OSM element (node, way, or relation).

    Parameters
    ----------
    element : dict
        OSM element from Overpass API

    Returns
    -------
    tuple (lat, lon) or (None, None) if not found
    """
    if element["type"] == "node":
        return element.get("lat"), element.get("lon")
    else:
        center = element.get("center", {})
        return center.get("lat"), center.get("lon")


def get_mrt_stations() -> pd.DataFrame:
    """
    Query OpenStreetMap for all public MRT/LRT stations in Singapore.
    Excludes private systems (Changi Skytrain, Sentosa Express).

    Returns
    -------
    pd.DataFrame with columns: station_name, lat, long
    """
    print("Fetching MRT/LRT stations...")

    query = """
    [out:json][timeout:60];
    area["ISO3166-1"="SG"]->.sg;
    (
      node["railway"="station"]["station"~"subway|light_rail|monorail"](area.sg);
      way ["railway"="station"]["station"~"subway|light_rail|monorail"](area.sg);
      rel ["railway"="station"]["station"~"subway|light_rail|monorail"](area.sg);
    );
    out center;
    """

    elements = query_overpass(query)
    rows = []

    for el in elements:
        tags = el.get("tags", {})
        name = tags.get("name", "Unknown")
        name_lower = name.strip().lower()
        operator = tags.get("operator", "").lower()
        network = tags.get("network", "").lower()

        # Skip entrance/exit nodes
        if tags.get("entrance") or tags.get("railway") == "subway_entrance":
            continue
        if name_lower.startswith("exit"):
            continue

        # Skip Changi Airport Skytrain
        if "changi" in operator or "changi" in network:
            continue
        if name_lower in CHANGI_SKYTRAIN_STATIONS:
            continue

        # Skip Sentosa Express
        if "sentosa" in operator or "sentosa" in network:
            continue
        if name_lower in SENTOSA_EXPRESS_STATIONS:
            continue

        lat, lon = get_coordinates(el)
        if lat and lon:
            rows.append({"station_name": name, "lat": lat, "long": lon})

    if not rows:
        print("Warning: No MRT/LRT stations found")
        return pd.DataFrame(columns=["station_name", "lat", "long"])

    df = (pd.DataFrame(rows)
          .drop_duplicates("station_name")
          .sort_values("station_name")
          .reset_index(drop=True))

    print(f"Found {len(df)} MRT/LRT stations")
    return df


